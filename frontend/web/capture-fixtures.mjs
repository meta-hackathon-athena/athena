// Regenerate public/fixtures.js from a running backend, so fixture mode (?fixtures=1)
// stays an exact snapshot of real API responses. Run it right after `make ui-demo`,
// before answering any question:
//
//   ATHENA_API=http://127.0.0.1:8765 node frontend/web/capture-fixtures.mjs

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const API = (process.env.ATHENA_API ?? "http://127.0.0.1:8765").replace(/\/$/, "") + "/v1";
const get = async (path) => {
  const res = await fetch(API + path);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
};

const health = await get("/health");
const { questions } = await get("/questions?status=open&limit=20");
const { memories } = await get("/memories?status=active,unconfirmed&limit=100");
const { commitments } = await get("/commitments");
const { reminders } = await get("/reminders?status=all");
const memoryDetails = {};
for (const m of memories) memoryDetails[m.id] = (await get(`/memories/${encodeURIComponent(m.id)}`)).memory;

const data = { captured_from: health.graph, questions, memories, memoryDetails, commitments, reminders };
const out = fileURLToPath(new URL("./public/fixtures.js", import.meta.url));
await writeFile(out, `// Offline snapshot of real /v1 responses, used only in fixture mode (?fixtures=1).
// Generated by frontend/web/capture-fixtures.mjs from graph ${health.graph}. Do not edit by hand.
export const FIXTURES = ${JSON.stringify(data, null, 2)};
`);
console.log(`wrote ${out}: ${questions.length} questions, ${memories.length} memories, ` +
            `${commitments.length} plans, ${reminders.length} reminders`);
